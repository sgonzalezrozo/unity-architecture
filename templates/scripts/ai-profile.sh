#!/usr/bin/env bash
# Writes the project profile the agents read instead of detecting packages themselves: which capabilities are true,
# and which branch folder each fork in the rules resolves to (OPT-06). It reads Packages/manifest.json and the table in
# .ai/capabilities.json, and writes Logs/ai/profile.json and Logs/ai/profile.md.
# It only regenerates when the manifest, the table, the paths the table checks or this script changed, so running it
# on every session start costs nothing. The Claude Code SessionStart hook runs it with --print, which puts the profile
# in the agent's context.
#
# Usage, from the project root:
#   scripts/ai-profile.sh            writes the profile when it's out of date
#   scripts/ai-profile.sh --print    also prints profile.md
#   scripts/ai-profile.sh --force    regenerates it even when it's up to date
set -u

PRINT=false
FORCE=false
for arg in "$@"; do
    case "$arg" in
        --print) PRINT=true ;;
        --force) FORCE=true ;;
        -h|--help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "Unknown option: $arg (use --print, --force or --help)"; exit 2 ;;
    esac
done

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TABLE="$ROOT/.ai/capabilities.json"
MANIFEST="$ROOT/Packages/manifest.json"
OUT="$ROOT/Logs/ai"
PROFILE_JSON="$OUT/profile.json"
PROFILE_MD="$OUT/profile.md"
HASH_FILE="$OUT/profile.hash"
BRANCHES=".ai/architecture/branches"

if [ ! -f "$TABLE" ]; then
    echo "No .ai/capabilities.json: run git submodule update --init, then try again."
    exit 2
fi

# Each capability line of the table as "id|packages|paths", the lists separated by spaces. Not tabs: read collapses
# consecutive tabs, so an empty list would shift the next field.
capability_lines() {
    grep '"packages"' "$TABLE" | sed 's/.*"id": *"\([^"]*\)".*"packages": *\[\([^]]*\)\].*"paths": *\[\([^]]*\)\].*/\1|\2|\3/' \
        | tr -d '"' | tr ',' ' '
}

# Each fork line as "id|capability:branch ...", in the table's order of preference.
fork_lines() {
    grep '"branches"' "$TABLE" | sed 's/.*"id": *"\([^"]*\)".*"branches": *\[\([^]]*\)\].*/\1|\2/' | tr -d '"' | tr ',' ' '
}

# The paths the table checks change detection too (scripts/verify.sh, a Zenject folder), so their existence is hashed.
input_hash() {
    {
        cat "$TABLE" "$0" 2>/dev/null
        cat "$MANIFEST" 2>/dev/null
        capability_lines | while IFS='|' read -r id packages paths; do
            for path in $paths; do
                [ -e "$ROOT/$path" ] && echo "exists: $path"
            done
        done
    } | cksum | awk '{ print $1 "-" $2 }'
}

# After the profile: the project facts and the task packs, each regenerating only what changed. With --print, the
# SessionStart hook shows the profile, the facts and the packs' index, so the agent starts with all three.
finish() {
    [ "$PRINT" = true ] && cat "$PROFILE_MD"
    local here
    here="$(dirname "$0")"
    if [ -x "$here/ai-facts.sh" ]; then
        if [ "$PRINT" = true ]; then "$here/ai-facts.sh" --print; else "$here/ai-facts.sh"; fi
    fi
    if [ -x "$here/ai-packs.sh" ]; then
        if [ "$PRINT" = true ]; then "$here/ai-packs.sh" --index; else "$here/ai-packs.sh"; fi
    fi
    exit 0
}

HASH="$(input_hash)"
if [ "$FORCE" = false ] && [ -f "$PROFILE_MD" ] && [ -f "$PROFILE_JSON" ] && [ "$(cat "$HASH_FILE" 2>/dev/null)" = "$HASH" ]; then
    finish
fi

# True when the manifest lists one of the packages, or one of the paths exists.
detect() {
    local packages="$1" paths="$2" package path
    for package in $packages; do
        grep -qs "\"$package\"" "$MANIFEST" && return 0
    done
    for path in $paths; do
        [ -e "$ROOT/$path" ] && return 0
    done
    return 1
}

TRUE_CAPS=""
FALSE_CAPS=""
CAPS_JSON=""
while IFS='|' read -r id packages paths; do
    if detect "$packages" "$paths"; then
        TRUE_CAPS="$TRUE_CAPS $id"
        CAPS_JSON="$CAPS_JSON, \"$id\": true"
    else
        FALSE_CAPS="$FALSE_CAPS $id"
        CAPS_JSON="$CAPS_JSON, \"$id\": false"
    fi
done < <(capability_lines)

is_true() {
    case " $TRUE_CAPS " in *" $1 "*) return 0 ;; esac
    return 1
}

# The first branch whose capability is true; * always matches.
FORKS_JSON=""
FORK_ROWS=""
while IFS='|' read -r id choices; do
    chosen=""
    for choice in $choices; do
        capability="${choice%%:*}"
        if [ "$capability" = "*" ] || is_true "$capability"; then
            chosen="${choice#*:}"
            break
        fi
    done
    FORKS_JSON="$FORKS_JSON, \"$id\": \"$chosen\""
    FORK_ROWS="$FORK_ROWS| \`$id\` | \`$chosen\` | \`$BRANCHES/$chosen/\` |
"
done < <(fork_lines)

list_or_none() {
    local list="${1# }"
    [ -n "$list" ] && echo "\`${list// /\`, \`}\`" || echo "none"
}

mkdir -p "$OUT"
printf '{ "profileVersion": 1, "source": "%s", "capabilities": { %s }, "forks": { %s } }\n' \
    "$HASH" "${CAPS_JSON#, }" "${FORKS_JSON#, }" > "$PROFILE_JSON"
cat > "$PROFILE_MD" <<EOF
# Project profile

Generated by \`scripts/ai-profile.sh\` from \`Packages/manifest.json\` and \`.ai/capabilities.json\`. Don't edit it: it's
regenerated when either changes. Use it instead of reading the manifest (\`OPT-06\`).

## Forks

At a fork in the rules, open only the file in the branch folder below. Never open another branch to compare.

| Fork | Branch | Folder |
|---|---|---|
$FORK_ROWS
## Capabilities

- \`true\`: $(list_or_none "$TRUE_CAPS")
- \`false\`: $(list_or_none "$FALSE_CAPS")

A rule that names a capability applies only when it's \`true\` (\`OPT-01\`).
EOF
echo "$HASH" > "$HASH_FILE"
finish
